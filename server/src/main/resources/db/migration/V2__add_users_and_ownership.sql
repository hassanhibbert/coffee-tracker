-- V2: users, and an owner on every row.
-- "user" is a reserved word in Postgres, hence app_users.
create table app_users (
    id            bigint generated by default as identity primary key,
    username      varchar(50)  not null unique,
    password_hash varchar(100) not null,
    created_at    timestamptz  not null default now()
);

-- NOT NULL without a default only works because no environment holds data yet.
-- With real data you would expand/contract: add the column nullable, backfill owners,
-- then add the NOT NULL constraint in a later migration.
alter table beans     add column owner_id bigint not null references app_users (id);
alter table equipment add column owner_id bigint not null references app_users (id);

-- Deliberate denormalization: a brew's owner is derivable via its bean, but storing it
-- directly lets "my brews" be one indexed lookup instead of a join on every request.
alter table brews     add column owner_id bigint not null references app_users (id);

create index idx_beans_owner_id on beans (owner_id);
create index idx_equipment_owner_id on equipment (owner_id);
-- Composite: serves "my brews, newest first" from the index alone, and its leading
-- column also serves any query filtering only on owner_id.
create index idx_brews_owner_brewed_at on brews (owner_id, brewed_at desc);
