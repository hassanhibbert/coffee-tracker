-- V1: core schema.
-- Never edit this file after it has been applied anywhere: Flyway stores a checksum
-- of every migration and refuses to start if an applied file changes. Add V2, V3... instead.

create table beans (
    id             bigint generated by default as identity primary key,
    name           varchar(100) not null,
    roast_level    varchar(20)  not null,
    country_origin varchar(60)  not null
);

create table equipment (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    brew_method varchar(20)  not null,
    brand       varchar(60)
);

create table brews (
    id                bigint generated by default as identity primary key,
    bean_id           bigint        not null references beans (id),
    equipment_id      bigint        not null references equipment (id),
    grind_size        varchar(20)   not null,
    coffee_grams      numeric(5, 1) not null check (coffee_grams > 0),
    water_grams       numeric(6, 1) not null check (water_grams > 0),
    water_temp_c      integer       check (water_temp_c between 0 and 100),
    brew_time_seconds integer       not null check (brew_time_seconds > 0),
    rating            integer       check (rating between 1 and 5),
    notes             varchar(2000),
    brewed_at         timestamptz   not null default now()
);

-- Postgres indexes primary keys automatically, but NOT foreign keys.
-- Without these, "brews for bean X" and the FK check on deleting a bean are full table scans.
create index idx_brews_bean_id on brews (bean_id);
create index idx_brews_equipment_id on brews (equipment_id);
